// Dialect bridge: the repos speak one portable SQL subset (`?` placeholders,
// camelCase identifiers, `ON CONFLICT ... DO UPDATE`). SQLite runs it as-is;
// Postgres needs placeholders renumbered and identifier case restored.
import { TABLES } from "./schema.js";

// Postgres folds unquoted identifiers to lowercase, so `createdAt` comes back
// as `createdat`. Map lowercase → declared camelCase so repos keep reading
// `row.createdAt`. Built from the schema, which is the only source of columns.
let CANONICAL = null; // built lazily — schema.js imports back into this module
function canonical() {
  if (!CANONICAL) {
    CANONICAL = new Map();
    for (const def of Object.values(TABLES)) {
      for (const col of Object.keys(def.columns)) CANONICAL.set(col.toLowerCase(), col);
    }
  }
  return CANONICAL;
}

export function canonicalizeRow(row) {
  if (!row) return row;
  const map = canonical();
  let out = null;
  for (const k of Object.keys(row)) {
    const canon = map.get(k);
    if (canon && canon !== k) {
      if (!out) out = { ...row };
      out[canon] = row[k];
      delete out[k];
    }
  }
  return out || row;
}

// `?` → `$1, $2, …`, skipping single-quoted literals and `--` comments.
export function toPgSql(sql) {
  let out = "";
  let n = 0;
  for (let i = 0; i < sql.length; i++) {
    const ch = sql[i];
    if (ch === "'") {
      const end = closingQuote(sql, i);
      out += sql.slice(i, end + 1);
      i = end;
    } else if (ch === "-" && sql[i + 1] === "-") {
      const end = sql.indexOf("\n", i);
      const stop = end === -1 ? sql.length : end;
      out += sql.slice(i, stop);
      i = stop - 1;
    } else if (ch === "?") {
      out += `$${++n}`;
    } else {
      out += ch;
    }
  }
  return out;
}

function closingQuote(sql, start) {
  for (let i = start + 1; i < sql.length; i++) {
    if (sql[i] !== "'") continue;
    if (sql[i + 1] === "'") { i++; continue; } // escaped ''
    return i;
  }
  return sql.length - 1;
}

// Column type translation for CREATE TABLE / ADD COLUMN.
const PG_COLUMN_RULES = [
  // SQLite rowid alias → identity column that still accepts explicit ids
  // (the sqlite→postgres copy script inserts ids verbatim).
  [/^INTEGER PRIMARY KEY AUTOINCREMENT$/i, "bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"],
  [/^INTEGER PRIMARY KEY$/i, "bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"],
  [/\bREAL\b/i, "double precision"],
];

export function columnDefFor(dialect, def) {
  if (dialect !== "postgres") return def;
  let out = def;
  for (const [re, repl] of PG_COLUMN_RULES) out = out.replace(re, repl);
  return out;
}

// `INSERT OR REPLACE` has no Postgres equivalent. Emit the portable upsert both
// engines accept; every call site lists all columns, so overwriting all
// non-key columns matches the old replace semantics.
export function upsertSql(table, columns, conflictColumns) {
  const conflict = new Set(conflictColumns);
  const updates = columns.filter((c) => !conflict.has(c)).map((c) => `${c} = excluded.${c}`);
  const sql = `INSERT INTO ${table}(${columns.join(", ")}) VALUES(${columns.map(() => "?").join(", ")}) ON CONFLICT(${conflictColumns.join(", ")})`;
  return updates.length ? `${sql} DO UPDATE SET ${updates.join(", ")}` : `${sql} DO NOTHING`;
}
