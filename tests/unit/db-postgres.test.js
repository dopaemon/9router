// Postgres / Supabase backend.
//
// The dialect-bridge tests always run. The round-trip tests need a real
// Postgres and are skipped without one:
//
//   docker run -d -e POSTGRES_PASSWORD=testpass -e POSTGRES_DB=ninerouter \
//     -p 54329:5432 postgres:16-alpine
//   TEST_POSTGRES_URL='postgresql://postgres:testpass@localhost:54329/ninerouter?sslmode=disable' \
//     npx vitest run unit/db-postgres.test.js
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { describe, it, expect, beforeAll, afterAll } from "vitest";
import { toPgSql, upsertSql, canonicalizeRow } from "@/lib/db/sqlDialect.js";
import { buildCreateTableSql, TABLES } from "@/lib/db/schema.js";

const PG_URL = process.env.TEST_POSTGRES_URL;

describe("dialect bridge", () => {
  it("renumbers placeholders left to right", () => {
    expect(toPgSql(`SELECT * FROM kv WHERE scope = ? AND key = ?`))
      .toBe(`SELECT * FROM kv WHERE scope = $1 AND key = $2`);
  });

  it("leaves ? inside string literals alone", () => {
    expect(toPgSql(`SELECT ? WHERE a = 'why? sure' AND b = ?`))
      .toBe(`SELECT $1 WHERE a = 'why? sure' AND b = $2`);
    expect(toPgSql(`SELECT ? WHERE a = 'it''s a ?' AND b = ?`))
      .toBe(`SELECT $1 WHERE a = 'it''s a ?' AND b = $2`);
  });

  it("leaves ? inside line comments alone", () => {
    expect(toPgSql(`SELECT ? -- what?\nAND b = ?`)).toBe(`SELECT $1 -- what?\nAND b = $2`);
  });

  it("builds an upsert that updates every non-key column", () => {
    expect(upsertSql("kv", ["scope", "key", "value"], ["scope", "key"]))
      .toBe(`INSERT INTO kv(scope, key, value) VALUES(?, ?, ?) ON CONFLICT(scope, key) DO UPDATE SET value = excluded.value`);
  });

  it("degrades to DO NOTHING when the key is the whole row", () => {
    expect(upsertSql("t", ["a"], ["a"])).toMatch(/DO NOTHING$/);
  });

  it("restores camelCase column names folded by postgres", () => {
    expect(canonicalizeRow({ createdat: "x", isactive: 1, c: 3 }))
      .toEqual({ createdAt: "x", isActive: 1, c: 3 });
  });

  it("maps the autoincrement rowid to an identity column", () => {
    const sql = buildCreateTableSql("usageHistory", TABLES.usageHistory, "postgres");
    expect(sql).toContain("GENERATED BY DEFAULT AS IDENTITY");
    expect(sql).not.toContain("AUTOINCREMENT");
    expect(sql).toContain("cost double precision DEFAULT 0");
    // SQLite output must be untouched
    expect(buildCreateTableSql("usageHistory", TABLES.usageHistory)).toContain("AUTOINCREMENT");
  });
});

describe.skipIf(!PG_URL)("postgres round-trip", () => {
  let db;
  let tempDir;

  beforeAll(async () => {
    tempDir = fs.mkdtempSync(path.join(os.tmpdir(), "9router-pg-"));
    process.env.DATA_DIR = tempDir;
    const { createPostgresAdapter } = await import("@/lib/db/adapters/postgresAdapter.js");
    db = await createPostgresAdapter(PG_URL);
    // Start from a clean schema so re-runs are deterministic.
    for (const t of Object.keys(TABLES)) await db.exec(`DROP TABLE IF EXISTS ${t} CASCADE`);
    const { runMigrationOnce } = await import("@/lib/db/migrate.js");
    await runMigrationOnce(db);
  });

  afterAll(async () => {
    await db?.close();
    if (tempDir) fs.rmSync(tempDir, { recursive: true, force: true });
  });

  it("creates every declared table", async () => {
    for (const t of Object.keys(TABLES)) {
      const cols = await db.listColumns(t);
      expect(cols.length, t).toBeGreaterThan(0);
    }
  });

  it("round-trips a row with camelCase columns", async () => {
    const now = new Date().toISOString();
    await db.run(
      upsertSql("providerConnections", ["id", "provider", "authType", "name", "isActive", "data", "createdAt", "updatedAt"], ["id"]),
      ["c1", "openai", "apikey", "acct", 1, JSON.stringify({ apiKey: "sk-x" }), now, now]
    );
    const row = await db.get(`SELECT * FROM providerConnections WHERE id = ?`, ["c1"]);
    expect(row.authType).toBe("apikey");
    expect(row.createdAt).toBe(now);
    expect(row.isActive).toBe(1);
    expect(JSON.parse(row.data).apiKey).toBe("sk-x");
  });

  it("upserts instead of duplicating", async () => {
    const sql = upsertSql("kv", ["scope", "key", "value"], ["scope", "key"]);
    await db.run(sql, ["pricing", "openai", "1"]);
    await db.run(sql, ["pricing", "openai", "2"]);
    const rows = await db.all(`SELECT value FROM kv WHERE scope = ? AND key = ?`, ["pricing", "openai"]);
    expect(rows).toHaveLength(1);
    expect(rows[0].value).toBe("2");
  });

  it("generates usageHistory ids without an explicit value", async () => {
    await db.run(
      `INSERT INTO usageHistory(timestamp, provider, model, promptTokens, cost) VALUES(?, ?, ?, ?, ?)`,
      [new Date().toISOString(), "openai", "gpt-4", 10, 0.5]
    );
    const row = await db.get(`SELECT id, cost FROM usageHistory ORDER BY id DESC LIMIT 1`);
    expect(Number(row.id)).toBeGreaterThan(0);
    expect(Number(row.cost)).toBe(0.5);
  });

  it("rolls the whole transaction back on throw", async () => {
    await expect(db.transaction(async (tx) => {
      await tx.run(`INSERT INTO combos(id, name, kind, models, createdAt, updatedAt) VALUES(?, ?, ?, ?, ?, ?)`,
        ["t1", "doomed", "fallback", "[]", "now", "now"]);
      throw new Error("boom");
    })).rejects.toThrow("boom");
    expect(await db.get(`SELECT * FROM combos WHERE id = ?`, ["t1"])).toBeUndefined();
  });

  it("commits writes made through the tx handle", async () => {
    await db.transaction(async (tx) => {
      await tx.run(`INSERT INTO combos(id, name, kind, models, createdAt, updatedAt) VALUES(?, ?, ?, ?, ?, ?)`,
        ["t2", "kept", "fallback", "[]", "now", "now"]);
    });
    expect((await db.get(`SELECT name FROM combos WHERE id = ?`, ["t2"]))?.name).toBe("kept");
  });

  it("re-runs migration idempotently", async () => {
    const { runMigrationOnce } = await import("@/lib/db/migrate.js");
    await runMigrationOnce(db); // same adapter → no-op
    const cols = await db.listColumns("apiKeys");
    expect(cols.map((c) => c.toLowerCase())).toContain("accessrestricted");
  });
});

describe.skipIf(!PG_URL)("repos against postgres", () => {
  let tempDir;
  const prevUrl = process.env.SUPABASE_DB_URL;

  beforeAll(async () => {
    tempDir = fs.mkdtempSync(path.join(os.tmpdir(), "9router-pgrepo-"));
    process.env.DATA_DIR = tempDir;
    process.env.SUPABASE_DB_URL = PG_URL;
    delete global._dbAdapter;
    // getAdapter() builds the schema itself via runMigrationOnce.
    const { getAdapter } = await import("@/lib/db/driver.js");
    await getAdapter();
  });

  afterAll(async () => {
    try { await global._dbAdapter?.instance?.close?.(); } catch {}
    delete global._dbAdapter;
    if (prevUrl === undefined) delete process.env.SUPABASE_DB_URL;
    else process.env.SUPABASE_DB_URL = prevUrl;
    if (tempDir) fs.rmSync(tempDir, { recursive: true, force: true });
  });

  it("selects the postgres driver from SUPABASE_DB_URL", async () => {
    const { getAdapter } = await import("@/lib/db/driver.js");
    expect((await getAdapter()).driver).toBe("postgres");
  });

  it("creates, lists, updates and deletes a connection through the repo", async () => {
    const repo = await import("@/lib/db/repos/connectionsRepo.js");
    const created = await repo.createProviderConnection({
      provider: "anthropic", authType: "apikey", name: "k1", apiKey: "sk-ant-1",
    });
    expect(created.id).toBeTruthy();
    expect(created.priority).toBe(1);

    const list = await repo.getProviderConnections({ provider: "anthropic" });
    expect(list.map((c) => c.name)).toContain("k1");

    const updated = await repo.updateProviderConnection(created.id, { apiKey: "sk-ant-2" });
    expect(updated.apiKey).toBe("sk-ant-2");

    expect(await repo.deleteProviderConnection(created.id)).toBe(true);
    expect(await repo.getProviderConnectionById(created.id)).toBeNull();
  });

  it("stores and reads settings", async () => {
    const { getSettings, updateSettings } = await import("@/lib/db/repos/settingsRepo.js");
    await updateSettings({ stickyRoundRobinLimit: 7 });
    expect((await getSettings()).stickyRoundRobinLimit).toBe(7);
  });

  it("validates an api key it just created", async () => {
    const { createApiKey, validateApiKey } = await import("@/lib/db/repos/apiKeysRepo.js");
    const k = await createApiKey("test", "machine-abc");
    expect(await validateApiKey(k.key)).toBe(true);
    expect(await validateApiKey("sk-nope")).toBe(false);
  });

  it("exports and re-imports the whole database", async () => {
    const { exportDb, importDb } = await import("@/lib/db/index.js");
    const dump = await exportDb();
    expect(Array.isArray(dump.apiKeys)).toBe(true);
    const back = await importDb(dump);
    expect(back.apiKeys).toHaveLength(dump.apiKeys.length);
  });
});
